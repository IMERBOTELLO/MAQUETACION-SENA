CREATE DATABASE ATENCION_MEDICA;
USE ATENCION_MEDICA;

CREATE TABLE USUARIO(
	ID_USUARIO INT AUTO_INCREMENT PRIMARY KEY,
	CORREO VARCHAR (150) NOT NULL UNIQUE,
    CONTRASEÑA VARCHAR (150) NOT NULL,
    ROL ENUM(
		'RECEPCIONISTA',
        'MEDICO',
        'LABORATORIO',
        'PACIENTE',
        'ADMINISTRADOR'
    ) NOT NULL
);

CREATE TABLE PACIENTE (
  ID_PACIENTE    INT AUTO_INCREMENT PRIMARY KEY,
  NOMBRE_PACIENTE VARCHAR(255) NOT NULL,
  DIRECCION      VARCHAR(150) NOT NULL,
  NUMERO_DOCUMENTO   INT NOT NULL UNIQUE,
  CORREO         VARCHAR(120) NOT NULL,
  TELEFONO       INT NOT NULL
);

CREATE TABLE MEDICO (
  ID_MEDICO INT AUTO_INCREMENT PRIMARY KEY,
  NOMBRE_MEDICO  VARCHAR(100) NOT NULL,
  ESPECIALIDAD     VARCHAR(80) NOT NULL,
  TELEFONO         VARCHAR(20) NOT NULL UNIQUE,
  CORREO           VARCHAR(120) NOT NULL
  );

CREATE TABLE CITA (
	ID_CITA INT AUTO_INCREMENT PRIMARY KEY,
	ID_PACIENTE INT NOT NULL,
    ID_MEDICO INT NOT NULL,
    FECHA_HORA DATETIME NOT NULL,
	ESTADO BOOLEAN NOT NULL,
    PENDIENTE BOOLEAN NOT NULL,
    FOREIGN KEY (ID_PACIENTE) REFERENCES PACIENTE (ID_PACIENTE), 
	FOREIGN KEY (ID_MEDICO) REFERENCES MEDICO (ID_MEDICO)
);

CREATE TABLE ATENCION_MEDICA (
	ID_ATENCION INT AUTO_INCREMENT PRIMARY KEY,
	DIAGNOSTICO VARCHAR(100) NOT NULL,
    OBSERVACIONES VARCHAR(100) NOT NULL,
    TRATAMIENTO VARCHAR(100) NOT NULL,
    ID_CITA INT NOT NULL UNIQUE,
    FECHA_ATENCION DATE NOT NULL,
    MOTIVO_CONSULTA VARCHAR(100) NOT NULL,
    FOREIGN KEY (ID_CITA) REFERENCES CITA (ID_CITA)
);

CREATE TABLE EXAMEN(
	ID_EXAMEN INT AUTO_INCREMENT PRIMARY KEY,
    ID_ATENCION INT NOT NULL UNIQUE,
    TIPO_EXAMEN VARCHAR(100) NOT NULL,
	FECHA DATE NOT NULL,
	ID_MEDICO INT NOT NULL,
    ID_PACIENTE INT NOT NULL,
	FOREIGN KEY (ID_ATENCION) REFERENCES ATENCION_MEDICA (ID_ATENCION)
);

CREATE TABLE LABORATORIO (
  ID_LAB            INT AUTO_INCREMENT PRIMARY KEY,
  NOMBRE_LAB        VARCHAR(100) NOT NULL,
  RESPONSABLE       VARCHAR(100),
  CORREO_LAB       VARCHAR(120),
  TELEFONO_CONTACTO VARCHAR(20)
);

CREATE TABLE  RESULTADO (
	ID_RESULTADO INT AUTO_INCREMENT PRIMARY KEY,
    ID_LAB INT NOT NULL,
    FECHA_RESULTADO DATE NOT NULL,
	ARCHIVO VARCHAR(255) NOT NULL,
	ID_EXAMEN INT NOT NULL,
    FOREIGN KEY (ID_EXAMEN) REFERENCES EXAMEN (ID_EXAMEN),
    FOREIGN KEY (ID_LAB) REFERENCES LABORATORIO (ID_LAB)
);

